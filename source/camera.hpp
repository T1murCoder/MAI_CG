#pragma once

#include <glm/glm.hpp>

#include "shader_types.hpp"

// Свободная камера: положение и направление взгляда (углы рыскания yaw и тангажа pitch);
// перемещается клавишами WASD/QE, поворачивается мышью с зажатой ПКМ.
// Проекция перспективная или ортографическая. Экспозиция и тон-маппинг — тоже свойства камеры,
// как выдержка у фотоаппарата
class Camera {
public:
	// Стартовый вид: из точки (2, 2, 3) на начало координат
	Camera();

	// Перемещает и поворачивает камеру по вводу с клавиатуры и мыши за прошедшие dt секунд;
	// ввод игнорируется, пока его перехватывает ImGui (курсор над окном UI, ввод текста)
	void update(double dt);

	// Записывает в uniform-данные сцены матрицу вида-проекции под соотношение сторон aspect,
	// положение камеры (нужно шейдеру для блика) и параметры тон-маппинга
	void fill(shader::SceneUniforms& uniforms, float aspect) const;

	// Тип проекции, положение, углы поворота, угол обзора, экспозиция и настройки управления
	// в текущем окне ImGui
	void drawUi();

private:
	// Матрица вида: переводит мировые координаты в систему координат камеры
	glm::mat4 view() const;

	// Матрица проекции под соотношение сторон окна, уже с поправкой на ось Y в clip space Vulkan
	glm::mat4 projection(float aspect) const;

	// Единичный вектор направления взгляда, вычисленный из yaw и pitch
	glm::vec3 forward() const;

	// Поворачивает камеру так, чтобы она смотрела на точку target
	void lookAt(glm::vec3 target);

	glm::vec3 position = glm::vec3(2.0f, 2.0f, 3.0f);
	glm::vec3 up = glm::vec3(0.0f, 1.0f, 0.0f);

	// yaw — поворот вокруг мировой оси Y (0° — взгляд вдоль +X, 90° — вдоль +Z);
	// pitch — наклон вверх/вниз, ограничен ±89°, чтобы вид не переворачивался
	float yaw_degrees = 0.0f;
	float pitch_degrees = 0.0f;

	bool perspective = true;
	float fov_degrees = 45.0f;      // вертикальный угол обзора перспективной проекции
	float ortho_half_height = 1.7f; // половина высоты видимой области ортографической проекции
	float near_plane = 0.1f;
	float far_plane = 100.0f;

	// Тон-маппинг Рейнхарда сжимает средние тона (1 → 0.5), поэтому экспозиция по умолчанию больше 1
	bool tone_mapping = true;
	float exposure = 1.5f; // множитель освещённости перед тон-маппингом

	float move_speed = 3.0f;          // единиц в секунду; с зажатым Shift — втрое быстрее
	float mouse_sensitivity = 0.15f; // градусов поворота на пиксель движения мыши
};
